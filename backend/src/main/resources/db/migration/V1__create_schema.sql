-- WAF Log Analyzer — MVP schema
-- Source of truth: docs/solution-design.md v1.6 §7.1 / §7.3
--
-- applications 1──N web_events 1──N detection_hits N──1 detection_rules
--                     │
--                     1
--                     │
--                     1 alerts N──1 incidents 1──N incident_work_notes
--
-- Alert is 1-1 with WebEvent and may be unattached (incident_id NULL)
-- until Incident Manager promotes it (IMMEDIATE / AGGREGATE).
-- Work notes are USER/SYSTEM insights persisted on the incident; they are
-- grounded context for LLM explain later (hits remain the detector evidence).

-- SOC auth — JWT access token is stateless; refresh token is persisted.
-- POST /api/oauth/tokens (solution-design §8).
-- RBAC maps RACI §10.2: operate / triage / edit rules.
-- Store SHA-256(token) only — never the raw refresh token.

-- ---------------------------------------------------------------------------
-- roles — one role per user (JWT claim `role`). Add rows here; do not hard-code in Java.
-- ---------------------------------------------------------------------------
CREATE TABLE roles
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32) NOT NULL,
    name        VARCHAR(64) NOT NULL,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_roles_code UNIQUE (code)
);

COMMENT
ON TABLE  roles IS 'SOC roles. JWT carries roles.code (ADMIN | ANALYST | VIEWER).';
COMMENT
ON COLUMN roles.code IS 'Stable identifier used in Spring @PreAuthorize / JWT. Uppercase, no spaces.';

-- ---------------------------------------------------------------------------
-- permissions — API capabilities (authority strings)
-- ---------------------------------------------------------------------------
CREATE TABLE permissions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)  NOT NULL,
    name        VARCHAR(128) NOT NULL,
    description TEXT,

    CONSTRAINT uq_permissions_code UNIQUE (code)
);

COMMENT
ON TABLE  permissions IS 'Fine-grained authorities. Spring: hasAuthority(code).';
COMMENT
ON COLUMN permissions.code IS 'resource:action — e.g. rules:write, incidents:triage.';

CREATE TABLE role_permissions
(
    role_id       BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,

    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id)
);

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role_id       BIGINT       NOT NULL REFERENCES roles (id),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_users_username UNIQUE (username)
);

COMMENT
ON TABLE  users IS 'SOC operators. One role per user for a simple JWT role claim.';
COMMENT
ON COLUMN users.password_hash IS 'BCrypt (Spring BCryptPasswordEncoder).';

CREATE INDEX idx_users_role ON users (role_id);

-- ---------------------------------------------------------------------------
-- refresh_tokens
-- ---------------------------------------------------------------------------
CREATE TABLE refresh_tokens
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash     CHAR(64)    NOT NULL,
    expires_at     TIMESTAMPTZ NOT NULL,
    revoked_at     TIMESTAMPTZ,
    replaced_by_id BIGINT REFERENCES refresh_tokens (id),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT chk_refresh_tokens_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'
)
    );

COMMENT
ON TABLE  refresh_tokens IS 'Opaque refresh tokens for JWT rotation. Lookup by SHA-256 hex of the token presented by the client.';
COMMENT
ON COLUMN refresh_tokens.token_hash IS 'SHA-256 hex (lowercase) of the refresh token. Do not store plaintext.';
COMMENT
ON COLUMN refresh_tokens.revoked_at IS 'Set on logout, rotation, or reuse detection. NULL = still valid (until expires_at).';
COMMENT
ON COLUMN refresh_tokens.replaced_by_id IS 'Token issued in rotation; previous row stays for reuse detection.';

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_active ON refresh_tokens (user_id, expires_at) WHERE revoked_at IS NULL;

